// Regenerates per-operation MDX stubs in content/docs/reference/ from openapi.yaml.
// Usage: node scripts/generate-openapi.mjs
//
// `<APIPage>` is registered globally via mdx-components.tsx, so generated MDX
// can reference it without an import.
//
// The script wipes every generated subdirectory under
// `content/docs/reference/` (one per OpenAPI tag) before writing so that paths
// or tags removed from `openapi.yaml` don't leave orphaned MDX files behind —
// orphans break `next build` because Next tries to prerender pages whose
// `<APIPage>` references a path no longer present in the spec. The
// hand-authored `index.mdx` is preserved, and the root `meta.json` is
// regenerated by the `beforeWrite` hook below — keep REFERENCE_META in sync
// with the hand-authored index and the desired sidebar structure.
//
// `content/docs/reference` is the collapsed API reference folder under Reference.
// Only this outer folder collapses. Tags are extracted beneath separators,
// making every generated endpoint a direct link while preserving page URLs.
// CLI lives under `(guide)/cli/`; MCP lives under `(guide)/context-routing/`.
// CLI commands are generated by scripts/generate-cli.mjs.

import { readdirSync, rmSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { generateFiles } from "fumadocs-openapi";
import { createOpenAPI } from "fumadocs-openapi/server";

import { chooseSpecSource } from "../lib/docs-sync/spec-source.mjs";
import { normalizeSpec } from "../lib/docs-sync/normalize-spec.mjs";

const OUTPUT_DIR = "./content/docs/reference";

// The document id that generated MDX references via `<APIPage document=... />`.
// It must match the input key used at runtime in lib/openapi.ts so the client
// component can look the spec up in the preloaded map.
const DOCUMENT_ID = "./openapi.yaml";

// Keep the outer API folder; endpoint families never require another expansion.
const REFERENCE_META = {
  title: "API reference",
  defaultOpen: false,
  collapsible: true,
};

// OpenAPI tag names are kept stable because they define public URL slugs.
// Override only their sidebar labels here so acronyms remain readable and the
// protocol groups describe the interface a caller is choosing.
const TAG_TITLES = {
  "openai-compatible": "OpenAI Chat Completions",
  "openai-responses": "OpenAI Responses",
  "anthropic-compatible": "Anthropic Messages",
  "google-compatible": "Google GenerateContent",
  discovery: "Models & providers",
  byok: "BYOK encryption",
  observability: "Metrics",
  health: "Health",
  management: "Cloud management",
};

const TAG_ORDER = [
  "openai-compatible",
  "openai-responses",
  "anthropic-compatible",
  "google-compatible",
  "discovery",
  "byok",
  "management",
  "observability",
  "health",
];

const MANAGEMENT_GROUPS = [
  ["Account & access", /Namespace|Account|AccessCode/],
  ["Billing & usage", /RequestSettlement|Billing|Checkout|UsageAggregate|Requests/],
  ["Provider keys", /Byok/],
  ["API keys", /ApiKey/],
  ["Policies & budgets", /Polic|Budget/],
  ["Presets", /Preset/],
  ["OAuth clients", /Oauth/],
];

function groupManagementPages(pages) {
  const remaining = new Set(pages);
  const grouped = [];

  for (const [title, pattern] of MANAGEMENT_GROUPS) {
    const matches = pages.filter((page) => remaining.has(page) && pattern.test(page));
    if (matches.length === 0) continue;
    grouped.push(`---${title}---`, ...matches);
    for (const page of matches) remaining.delete(page);
  }

  // New operations stay visible even before they receive a task group.
  if (remaining.size > 0) grouped.push("---Other---", ...remaining);
  return grouped;
}

// Subdirectories this script must NOT wipe. Everything under reference/ is
// generated per OpenAPI tag; the single-page CLI manual lives in (guide)/cli/.
const PRESERVED_DIRS = new Set();

// Wipe generated subdirectories (one per tag). Keep `index.mdx` and any
// other hand-authored top-level files — the only top-level write the
// generator does is `meta.json`, regenerated unconditionally.
for (const entry of readdirSync(OUTPUT_DIR, { withFileTypes: true })) {
  if (entry.isDirectory() && !PRESERVED_DIRS.has(entry.name)) {
    rmSync(join(OUTPUT_DIR, entry.name), { recursive: true, force: true });
  }
}

const spec = chooseSpecSource(process.env);
let rawSpec;
if (spec.kind === "url") {
  const res = await fetch(spec.value, { headers: { "User-Agent": "bitrouter-docs-openapi" } });
  if (!res.ok) throw new Error(`OpenAPI fetch ${res.status} from ${spec.value}`);
  rawSpec = await res.text();
  console.log(`generate-openapi: fetched spec from ${spec.value}`);
} else {
  rawSpec = readFileSync(spec.value, "utf8");
}
// Hoist nested `$defs` to the document root so fumadocs-openapi v11's ref
// parser can resolve the spec's root-absolute `#/$defs/...` pointers.
const document = normalizeSpec(rawSpec);
// OpenAPI permits operation tags without top-level declarations. Fumadocs only
// generates declared tags, so derive missing declarations rather than drop APIs.
const declaredTags = new Set((document.tags ?? []).map((tag) => tag.name));
document.tags ??= [];
for (const item of [...Object.values(document.paths ?? {}), ...Object.values(document.webhooks ?? {})]) {
  for (const method of ["get", "post", "put", "patch", "delete", "head", "options", "trace"]) {
    const operation = item?.[method];
    if (!operation) continue;
    operation.tags = operation.tags?.length ? operation.tags : ["other-endpoints"];
    for (const name of operation.tags) {
      if (declaredTags.has(name)) continue;
      document.tags.push({ name });
      declaredTags.add(name);
    }
  }
}
const openapi = createOpenAPI({ input: { [DOCUMENT_ID]: document } });

await generateFiles({
  input: openapi,
  output: OUTPUT_DIR,
  per: "operation",
  groupBy: "tag",
  includeDescription: true,
  meta: { folderStyle: "folder" },
  beforeWrite(files) {
    const root = files.find((f) => f.path === "meta.json");
    if (!root) throw new Error("Missing generated API reference metadata");
    const groups = files.flatMap((file) => {
      const match = file.path.match(/^([^/]+)\/meta\.json$/);
      return match ? [{ file, slug: match[1] }] : [];
    });
    // Known families keep their order; new tags remain visible automatically.
    const rank = (slug) => TAG_ORDER.includes(slug) ? TAG_ORDER.indexOf(slug) : TAG_ORDER.length;
    groups.sort((a, b) => rank(a.slug) - rank(b.slug) || a.slug.localeCompare(b.slug));
    const pages = ["index", "decisions", "chat-completions-messages"];
    for (const { file, slug } of groups) {
      const meta = JSON.parse(file.content);
      const title = TAG_TITLES[slug] ?? meta.title ?? slug;
      if (slug === "management") meta.pages = groupManagementPages(meta.pages ?? []);
      file.content = JSON.stringify({ ...meta, title }, null, 2) + "\n";
      const endpoints = (meta.pages ?? []).filter((page) => !page.startsWith("---"));
      if (endpoints.length > 0) {
        pages.push(`---${title}---`, `...${slug}`);
      }
    }
    root.content = JSON.stringify({ ...REFERENCE_META, pages }, null, 2) + "\n";
  },
});

console.log("Generated API Reference MDX from openapi.yaml");
