// Deterministic, offline generation from the committed schema snapshot.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { renderConfigReference } from '../lib/config-reference.mjs';
const raw = readFileSync('config-reference/schema.json', 'utf8');
const source = JSON.parse(readFileSync('config-reference/source.json', 'utf8'));
if (createHash('sha256').update(raw).digest('hex') !== source.sha256) {
  throw new Error('Configuration schema checksum mismatch. Refresh with pnpm snapshot:config; never hand-edit the snapshot.');
}
const schema = JSON.parse(raw);
if (!/^[a-f0-9]{40}$/.test(source.revision) || !schema.$id.includes(`/v${source.version}/`)) {
  throw new Error('Invalid configuration source metadata');
}
const base = `${source.repository}/blob/${source.revision}`;
const intro = readFileSync('config-reference/index.md', 'utf8')
  .replaceAll('{{VERSION}}', source.version)
  .replaceAll('{{REVISION}}', source.revision.slice(0, 12))
  .replaceAll('{{SOURCE_DATE}}', source.sourceDate.slice(0, 10))
  .replaceAll('{{SOURCE_BASE}}', base);
const content = `${intro.trimEnd()}\n\n{/* Generated by scripts/generate-config.mjs. Edit config-reference/index.md or refresh the pinned schema; do not edit this page. */}\n\n${renderConfigReference(schema)}`;
const outputs = [['content/docs/configuration-reference.mdx', content], ['public/schemas/bitrouter.config.schema.json', raw]];
if (process.argv.includes('--check')) {
  for (const [path, expected] of outputs) {
    if (readFileSync(path, 'utf8') !== expected) throw new Error(`${path} is stale; run pnpm generate:config`);
  }
  console.log('Configuration reference and downloadable schema match the pinned snapshot.');
} else {
  mkdirSync('public/schemas', { recursive: true });
  for (const [path, expected] of outputs) writeFileSync(path, expected);
  console.log(`Generated configuration reference (${Object.keys(schema.properties).length} root fields, ${Object.keys(schema.$defs).length} types; ${source.version}).`);
}
