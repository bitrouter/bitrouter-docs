// Emits the date of the newest changelog entry worth interrupting someone for,
// which drives the docs-section tab's unseen dot
// (components/changelog/use-changelog-unseen.ts).
//
// Routine releases are excluded on purpose: the dot used to fire off the newest
// entry of any kind, so an alpha bump pinged every visitor exactly as loudly as
// a real launch. Only notable/highlight entries move it now.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { parseEntry, resolveSignificance } from "../lib/changelog-entry.mjs";
import { compareVersionsDesc } from "../lib/release-version.mjs";

const DIR = "content/changelog";
const OUT = "lib/changelog-latest.ts";

let files = [];
try {
  files = (await readdir(DIR)).filter((f) => f.endsWith(".mdx"));
} catch {
  // No changelog dir yet — emit an empty date.
}

let latest = "";
const entries = [];
for (const file of files) {
  const { frontmatter: fm, body } = parseEntry(await readFile(join(DIR, file), "utf8"));
  if (typeof fm?.date !== "string") continue;
  entries.push({ ...fm, body, slug: file.replace(/\.mdx$/, "") });
  if (resolveSignificance(fm) === "routine") continue;
  // ISO YYYY-MM-DD strings compare correctly lexicographically.
  if (fm.date > latest) latest = fm.date;
}

await writeFile(
  OUT,
  `// Generated by scripts/generate-changelog-latest.mjs — do not edit.\n` +
    `// Newest notable/highlight entry; routine releases deliberately excluded.\n` +
    `export const LATEST_CHANGELOG_DATE = ${JSON.stringify(latest)};\n`,
);
console.log(`Wrote ${OUT} (latest notable=${latest || "none"})`);

// Keep the full changelog in the docs/search/LLM source as one import-free page.
// Release files remain the input for sync, announcements, and RSS/Atom.
entries.sort((a, b) =>
  b.date.localeCompare(a.date) || compareVersionsDesc(a.version, b.version) || b.slug.localeCompare(a.slug),
);
const page = [
  "---",
  "title: Changelog",
  "description: Product updates and release notes for BitRouter, newest first.",
  "---",
  "",
  "{/* GENERATED by scripts/generate-changelog-latest.mjs from content/changelog/. Edit the release files and regenerate. */}",
  "",
  "Every release on one page. Subscribe with [RSS](/changelog/rss.xml) or [Atom](/changelog/atom.xml).",
  ...entries.map((entry) => {
    // The filename matches the slug produced from the version heading, preserving
    // old release permalinks. Other title shapes get an explicit stable anchor.
    const title = entry.version ?? entry.title;
    const headingSlug = title.toLowerCase().replace(/[^\w\s-]/g, "").replace(/\s/g, "-");
    let inFence = false;
    const body = entry.body.replace(/\r\n?/g, "\n").split("\n").map((line) => {
      if (/^\s*```/.test(line)) inFence = !inFence;
      // All release subheadings belong beneath the version, never beside it.
      return !inFence ? line.replace(/^#{1,2} /, "### ") : line;
    }).join("\n");
    return [
      "",
      ...(headingSlug === entry.slug ? [] : [`<a id="${entry.slug}" />`, ""]),
      `## ${title}`,
      "",
      `${entry.date}${entry.breaking ? " · **Breaking changes**" : ""}`,
      "",
      ...(resolveSignificance(entry) !== "routine" && entry.description ? [entry.description, ""] : []),
      body,
    ].join("\n");
  }),
  "",
].join("\n");
await writeFile("content/docs/changelog.mdx", page);
console.log(`Wrote content/docs/changelog.mdx (${entries.length} releases)`);
